def main() -> None:
    connection = connect_week2()
    try:
        profile = connection.sql("""
            SELECT
                COUNT(*) AS behavior_count,
                COUNT(DISTINCT user_id) AS user_count,
                COUNT(DISTINCT content_id) AS content_count,
                MIN(event_date) AS first_event_date,
                MAX(event_date) AS last_event_date
            FROM behavior_fact
        """).df()

        questions = pd.DataFrame(QUESTIONS)
        metrics = pd.DataFrame(METRICS)
        profile_row = profile.iloc[0]

        report = f"""# Day 8: Business Questions

## Project background

This project uses the public MovieLens 25M dataset to simulate a content-platform growth and recommendation analysis. The data contains rating and tag activity, not a real company's product logs. A rating event is therefore used as a proxy for a user activity event.

The current data contains {int(profile_row['behavior_count']):,} rating records, {int(profile_row['user_count']):,} users, and {int(profile_row['content_count']):,} movies from {profile_row['first_event_date']} to {profile_row['last_event_date']}.

## Business questions

### 1. Which users may be churning?

Use the last observed rating date, activity frequency, cohort, and D7/D30 return behaviour to identify users or segments that require re-engagement analysis. The result is a churn proxy, not a confirmed churn label.

### 2. Which content drives high activity?

Rank content by distinct active users and rating volume, then compare average rating and genre. Do not rank only by average rating because low-volume titles can be unstable.

### 3. Why do metrics fluctuate?

Compare DAU, rating volume, active content, and new-user proxy against a historical moving average, standard deviation, and change-rate threshold. For each flagged date, check whether the movement is broad user activity, content concentration, new-user change, or a possible data issue.

## Required decisions from the analysis

- Define which user segment should be targeted by a re-engagement or recommendation test.
- Identify content or genres worth investigating as recommendation candidates.
- Define the anomaly threshold and the first diagnostic query to run when it fires.

## Data limitations

MovieLens does not include registration, exposure, click, watch-time, device, channel, campaign, or product-release data. It cannot prove why users churned or why an indicator moved. All findings must be presented as a simulated public-data analysis.

Generated on: {date.today().isoformat()}
"""

        questions.to_csv(
            OUTPUT_DIR / "ml_day08_business_questions.csv",
            index=False,
            encoding="utf-8-sig",
        )
        metrics.to_csv(
            OUTPUT_DIR / "ml_day08_metric_definitions.csv",
            index=False,
            encoding="utf-8-sig",
        )
        (OUTPUT_DIR / "ml_day08_business_questions.md").write_text(
            report,
            encoding="utf-8",
        )
        print("Saved Day 8 business questions and metric definitions.")
    finally:
        connection.close()


if __name__ == "__main__":
    main()
